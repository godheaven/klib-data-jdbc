package cl.kanopus.jdbc.impl.engine;

/**
 * Engine specific SQL generation. Every database dialect supported by the library implements this interface; dialect specific fragments (date casts, timestamp parsing, string concatenation, JSON binding) are generated here instead of being hard-coded in the generic code.
 */
public interface CustomEngine {

    /** Pattern accepted by {@link #toTimestamp(String, String)} for dates. */
    String DATE_PATTERN = "YYYY-MM-DD";

    /** Pattern accepted by {@link #toTimestamp(String, String)} for date and time. */
    String DATETIME_PATTERN = "YYYY-MM-DD HH24:MI:SS";

    StringBuilder createSqlPagination(String sql, int limit, int offset);

    String createSqlNextval(String sequence);

    /**
     * Translates SQL written with the PostgreSQL idioms generated by {@code SQLQueryDynamic} (for example {@code ::date}, {@code ||}, {@code TO_TIMESTAMP}) to this engine.
     *
     * @param sql
     *            the SQL to translate
     * @return SQL valid for the engine
     */
    String prepareSQL2Engine(String sql);

    /**
     * @param column
     *            column (or expression) to convert
     * @return SQL expression that truncates a timestamp column to a date
     */
    default String castToDate(String column) {
        return "CAST(" + column + " AS DATE)";
    }

    /**
     * @param parameterName
     *            named parameter (without colon) holding a text value
     * @param pattern
     *            {@link #DATE_PATTERN} or {@link #DATETIME_PATTERN}
     * @return SQL expression that converts the text parameter to a timestamp
     */
    default String toTimestamp(String parameterName, String pattern) {
        return "TO_TIMESTAMP(:" + parameterName + ", '" + pattern + "')";
    }

    /**
     * @param parts
     *            SQL expressions to concatenate
     * @return SQL expression concatenating the parts
     */
    default String concat(String... parts) {
        return String.join("||", parts);
    }

    /**
     * @param json
     *            JSON text
     * @return the value to bind for a JSON column (a plain String by default)
     */
    default Object toJsonParameter(String json) {
        return json;
    }
}
